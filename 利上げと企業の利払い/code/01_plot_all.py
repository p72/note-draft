import sys, pandas as pd, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
sys.path.insert(0,'<estat-api スキルのディレクトリ>')
from scripts.estat_api import setup_japanese_font; print(setup_japanese_font())
o=pd.read_csv('ratio.csv',index_col=0); o.index=pd.PeriodIndex(o.index,freq='Q').to_timestamp(how='end')
o=o.loc['1970':]
net=o.net_26.where(o.index>='1986-01-01')
fig,(a1,a3)=plt.subplots(2,1,figsize=(11,10),gridspec_kw={'height_ratios':[3,2]})
a1.plot(o.index,o.gross_26,color='#c0392b',lw=2,label='支払利息等 ÷ 経常利益（左軸）')
a1.plot(o.index,o.op_26,color='#e67e22',lw=1.5,label='支払利息等 ÷ 営業利益（左軸）')
a1.plot(o.index,net,color='#8e44ad',lw=1.3,ls='-.',label='(支払利息等−受取利息等) ÷ 経常利益（左軸, 1986〜）')
a1.axhline(0,color='gray',lw=.8); a1.set_ylim(-30,180); a1.set_ylabel('%')
a1.annotate(f'1975年 {o.gross_26.max():.0f}%',xy=(pd.Timestamp('1975-09-30'),178),xytext=(pd.Timestamp('1979-01-01'),165),arrowprops=dict(arrowstyle='->'),fontsize=9)
a2=a1.twinx(); a2.plot(o.index,o.call,'k--',lw=1.3,label='コールレート翌日物（右軸）'); a2.set_ylim(-2.4,14.4); a2.set_ylabel('%')
h1,l1=a1.get_legend_handles_labels(); h2,l2=a2.get_legend_handles_labels(); a1.legend(h1+h2,l1+l2,loc='upper right',fontsize=9)
a1.set_title('日本の法人企業：利払い負担（利益比）vs 短期金利\n全産業（除く金融保険業）・全規模、後方4四半期合計ベース',fontsize=12)
a1.grid(alpha=.3)
a3.plot(o.index,o.eff_26,color='#2c7fb8',lw=2,label='実効借入金利 = 支払利息等 ÷ 有利子負債（借入金+社債）')
a3.plot(o.index,o.call,'k--',lw=1.3,label='コールレート翌日物')
a3.set_ylabel('%'); a3.grid(alpha=.3); a3.legend(fontsize=9); a3.set_title('企業が実際に払っている金利 vs 政策金利',fontsize=11)
a3.axhline(0,color='gray',lw=.8)
fig.text(.01,.005,'出所：財務省「法人企業統計調査」（e-Stat）、日本銀行（コールレート：1985年6月以前は有担保、以降は無担保O/N月平均の四半期平均）。直近2026年4-6月期',fontsize=8)
plt.tight_layout(rect=(0,.02,1,1)); plt.savefig('../01_chart_all.png',dpi=150)
